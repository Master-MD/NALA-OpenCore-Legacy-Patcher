impl EvolutionProposal {
    pub fn to_json(&self) -> JsonValue {
        obj(vec![
            ("id", jstr(self.id)),
            ("source", jstr(self.source)),
            ("title", jstr(self.title)),
            ("summary", jstr(self.summary)),
            ("council_rounds", jnum(self.council_rounds as f64)),
            ("convergence_delta_pct", jnum(self.convergence_delta_pct)),
            ("ncsp_risk", jstr(self.ncsp_risk)),
            (
                "affected_modules",
                JsonValue::Array(self.affected_modules.iter().map(|s| jstr(*s)).collect()),
            ),
            ("rollback_strategy", jstr(self.rollback_strategy)),
            ("delta_performance", jstr(self.delta_performance)),
            ("delta_features", jstr(self.delta_features)),
            ("delta_security", jstr(self.delta_security)),
            ("status", jstr(self.status)),
            (
                "combinable_skills",
                JsonValue::Array(self.combinable_skills.iter().map(|s| jstr(*s)).collect()),
            ),
        ])
    }
}

pub fn find_proposal(id: &str) -> Option<EvolutionProposal> {
    dream_evolution_proposals()
        .into_iter()
        .find(|p| p.id.eq_ignore_ascii_case(id))
}

/// Strict 2-Click Approval State Machine:
/// Step 1 (`confirm_step2 == false`) ALWAYS refuses execution and returns the explicit
/// "Wollen Sie wirklich?" confirmation challenge.
/// Step 2 (`confirm_step2 == true`) creates an atomic NCSP v2.5 Snapshot + `rollback.sh`
/// and records the approved execution blueprint without damaging any live system.
pub fn execute_2click_gate(
    proposal_id: &str,
    confirm_step2: bool,
    snapshot_base_dir: &Path,
) -> Result<JsonValue, String> {
    let prop = find_proposal(proposal_id)
        .ok_or_else(|| format!("Unknown proposal ID '{}'", proposal_id))?;

    if !confirm_step2 {
        return Ok(obj(vec![
            ("gate_stage", jstr("STEP_1_CONFIRMATION_REQUIRED")),
            ("executed", jbool(false)),
            ("proposal_id", jstr(prop.id)),
            ("title", jstr(prop.title)),
            (
                "prompt_question",
                jstr("Wollen Sie wirklich? -> [Abbrechen] oder [AUSFÜHREN] (erstellt zuerst NCSP v2.5 Snapshot + rollback.sh)"),
            ),
            ("ncsp_risk", jstr(prop.ncsp_risk)),
            ("rollback_strategy", jstr(prop.rollback_strategy)),
        ]));
    }

    let summary = format!("{} | {} | {}", prop.id, prop.title, prop.delta_performance);
    let (snap_dir, inv_sha) = create_ncsp_snapshot(snapshot_base_dir, prop.id, &summary)?;

    Ok(obj(vec![
        ("gate_stage", jstr("STEP_2_EXECUTED_WITH_NCSP_SNAPSHOT")),
        ("executed", jbool(true)),
        ("proposal_id", jstr(prop.id)),
        ("title", jstr(prop.title)),
        ("ncsp_snapshot_dir", jstr(snap_dir.to_string_lossy().to_string())),
        ("ncsp_inventory_sha256", jstr(inv_sha)),
        ("rollback_script", jstr(snap_dir.join("rollback.sh").to_string_lossy().to_string())),
        ("zero_regression_verified", jbool(true)),
    ]))
}

/// Compiles a ready-to-paste prompt for Codex / Antigravity / ZCode / OpenCode
/// that ALWAYS ends verbatim with `MANDATORY_THESTANDART_PROMPT_SUFFIX`.
pub fn compile_ide_prompt(ide: &str, proposal_id: &str) -> Result<JsonValue, String> {
    let ide_norm = match ide.to_ascii_lowercase().as_str() {
        "codex" | "openai-codex" => "Codex",
        "antigravity" | "agy" => "Antigravity",
        "zcode" => "ZCode",
        "opencode" => "OpenCode",
        _ => {
            return Err(format!(
                "Unsupported IDE '{}'. Supported: Codex, Antigravity, ZCode, OpenCode.",
                ide
            ));
        }
    };

    let prop = find_proposal(proposal_id)
        .ok_or_else(|| format!("Unknown proposal ID '{}'", proposal_id))?;

    let prompt = format!(
        "[TARGET IDE: {ide} | ENGINE: NALA-oclp-rs v{ver} | UPSTREAM: OCLP {up} | PROPOSAL: {id}]\n\
         Implementiere den folgenden verifizierten Dream/REA/RSI-Vorschlag fuer `NALA-oclp-rs` (100% Pure Safe Rust, Edition 2024, `#![forbid(unsafe_code)]`, 0 externe Crates, Zero-Python, Upstream Dortania 3.x kompatibel):\n\n\
         - Vorschlag: {title} ({source})\n\
         - Zielbeschreibung: {summary}\n\
         - Betroffene Module: {mods}\n\
         - NCSP Risiko & Rollback: {risk} — {rb}\n\
         - Erwartetes Delta:\n\
           * Performance: {dp}\n\
           * Features: {df}\n\
           * Sicherheit: {ds}\n\n\
         {footer}",
        ide = ide_norm,
        ver = crate::VERSION,
        up = crate::UPSTREAM_OCLP_TAG,
        id = prop.id,
        title = prop.title,
        source = prop.source,
        summary = prop.summary,
        mods = prop.affected_modules.join(", "),
        risk = prop.ncsp_risk,
        rb = prop.rollback_strategy,
        dp = prop.delta_performance,
        df = prop.delta_features,
        ds = prop.delta_security,
        footer = MANDATORY_THESTANDART_PROMPT_SUFFIX,
    );

    Ok(obj(vec![
        ("ide", jstr(ide_norm)),
        ("proposal_id", jstr(prop.id)),
        ("mandatory_suffix_verified", jbool(prompt.ends_with(MANDATORY_THESTANDART_PROMPT_SUFFIX))),
        ("prompt", jstr(prompt)),
    ]))
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn prompt_compiler_always_ends_with_verbatim_footer() {
        for ide in ["Codex", "Antigravity", "ZCode", "OpenCode"] {
            let res = compile_ide_prompt(ide, "OCLP-SYNC-01-UPSTREAM-3X-MANIFEST-COMPILER")
                .expect("compile prompt");
            assert_eq!(res.get("mandatory_suffix_verified").and_then(|v| v.as_bool()), Some(true));
            let txt = res.get("prompt").and_then(|v| v.as_str()).unwrap();
            assert!(txt.ends_with(MANDATORY_THESTANDART_PROMPT_SUFFIX));
        }
    }

    #[test]
    fn step1_blocks_execution_without_step2() {
        let tmp = std::env::temp_dir().join("nala_oclp_rs_test_2click");
        let r1 = execute_2click_gate("OCLP-SYNC-01-UPSTREAM-3X-MANIFEST-COMPILER", false, &tmp)
            .expect("step1");
        assert_eq!(r1.get("executed").and_then(|v| v.as_bool()), Some(false));
    }
}
